## A timeline in lanes

*Event modeling* is a way of designing an information system as a story told left to right: a
screen (`ui`) leads to a command (`cmd`), which records an event (`evt`), which updates a read
model (`rmo`) that a screen shows. Each step is a *frame*, and each kind of step has its own
horizontal lane:
"""

let emText = """eventmodeling
tf 01 ui Cart
tf 02 cmd AddItem { id: 7 }
tf 03 evt ItemAdded
tf 04 rmo CartItems
tf 05 ui Checkout ->> 04
"""

nbText: &"""
```mermaid
{emText.strip}
```
"""

nbCode:
  let emSvg = render(emText).svg
  echo "identical to Pele's: ", emSvg == peleSvg(emText)

nbSvg emSvg, "An event model drawn by nimaki."

nbText: """
A frame in a new lane starts under the end of the frame before it, so the arrow between them can
drop straight down; a frame with no `->>` is fed by the nearest earlier frame in another lane.
This grammar is Langium-style again, with the tokenizer of pie and radar, and it uses the
`accDescr` token that remembers an unclosed brace, as treeview does. On a phone the frames become a column
of cards, and an arrow that skips cards runs down a *rail* beside them, a new rail for each run
that overlaps another.

nimaki has one small difference of shape here. Pele keeps maps whose keys are the boxes and lanes
themselves, which a Nim table cannot hash without help, so each box carries its place in the list
(`order`) and the maps use that. The drawing does not change.
"""

