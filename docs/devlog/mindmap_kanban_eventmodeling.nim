## An outline, read with states

A mindmap is written as an indented outline: each line is a node, and a node's parent is the last
node above it that is indented less. Brackets give a node its shape: `[square]`, `(rounded)`,
`((circle))`, `))bang((`, `)cloud(`, `{{{{hexagon}}}}`.
"""

let mindmapText = """mindmap
  root((nimaki))
    Port
      Lexers
      Layouts
    Check
      [Referee]
      (Fuzzer)
    Explain
      Devlog
      ::icon(mdi:book)
"""

nbText: &"""
```mermaid
{mindmapText.strip}
```
"""

nbText: """
Mermaid reads this with a grammar generated by Jison, whose lexer has *states*: inside a node's
brackets, `)` closes the node; outside, it opens a cloud. Pele's `outline.ts` writes that lexer by
hand as a loop over the characters with a `state` variable, and nimaki's `outline.nim` is the same
loop. Here are the tokens of the first lines:
"""

nbCode:
  let toks = outline.tokenize("mindmap\n  root((nimaki))\n    Port\n", false)
  for k in 0 ..< toks.types.len:
    echo tokenName(toks.types[k], false).alignLeft(12), " ", escape(toks.texts[k])

nbText: """
`SPACELIST` is the indentation, and its length is the node's level. The last token is the end
of the input, which the generated parser has no name for and prints as its number, `1`. The parser then makes the
calls that Mermaid's grammar actions make, in the same order, so the tree and the errors come out
the same. One thing is a little surprising: a parent is the last node *indented less*, wherever it
is, so an outline with uneven indentation still makes a tree, sometimes not the one you meant.

## A tree that spreads both ways

The mindmap layout puts the root in the middle and sends the first branches to the right and the
rest to the left. Where to split? Pele adds the heights of the branches and splits where the two
sides are closest in height. Each subtree is a *band*: its children's bands are stacked, and the
node sits at the middle of its first and last child, so a parent always faces its children.
"""

nbCode:
  let mindmapSvg = render(mindmapText).svg
  echo "identical to Pele's: ", mindmapSvg == peleSvg(mindmapText)

nbSvg mindmapSvg, "A mindmap drawn by nimaki; Pele draws the same bytes."

nbText: """
On a phone a tree spreading both ways does not fit, so Pele draws it as an outline instead: the
root on top and each level set in under its parent, with a trunk line that turns in to each child.
"""

