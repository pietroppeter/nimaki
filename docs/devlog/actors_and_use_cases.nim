## JSON, as V8 reads it

A `json` node holds a JSON object, drawn as a table of its leaves. Pele parses it with
`JSON.parse`, and when that fails it reports the engine's own message, with the line and column
it works out from the position in it. Node runs V8, and V8 has about twenty messages, some with a
position and some with a piece of the text around the bad character. Nim's `std/json` is more
lenient (it reads comments and trailing commas) and words its errors its own way, so the port
has a small JSON parser of its own that walks the text as V8's does and stops at the same
character:
"""

nbCode:
  for text in ["{\"a\": tru}", "{\"a\": 01}", "{a: 1}", "{\"a\": 1,}", "{\"a\": \"\\q\"}",
               "{\"a\": 1, \"a long key here\": x}"]:
    try:
      discard jsonParse(text)
    except CatchableError as e:
      echo text.alignLeft(32), " ", e.msg

nbText: """
Before writing the rest of the port, this parser was compared with Node's `JSON.parse` on
20,000 random, mostly broken texts: the same message for every one of them.

Once the text is JSON, the order of its keys matters, because the table lists them as written.
`JSON.parse` loses that order for keys that look like numbers (JavaScript puts `"1"` before
`"2"`, and both before `"name"`, whatever the text says), so Pele walks the text a second time to
recover it, keyed by JSON Pointer (`/address/city`). The port does the same.
"""

nbNote """
- **Bytes and code units.** The lexer reads UTF-8 bytes
  ([decision 0011](../../decisions/)); every test in it is of an ASCII character, which reads the
  same on bytes. The positions in messages are turned into UTF-16 code units, as JavaScript
  counts them, and so are the positions in V8's JSON messages.
- **An id made from a label.** `"Place order"` gets the id `Place_order`: every character that
  is not a word character becomes `_`. JavaScript replaces each UTF-16 code unit, so an emoji
  becomes `__`; the port counts the same way.
- **What is left out.** Pele also records each statement of the text with the positions of its
  parts, for editors. Nothing it draws reads them, so the port leaves them out, and says so in
  `types.nim`.
- **Closures in a loop.** Pele sorts the declarations by offset and runs a closure for each. In
  Nim, closures made in one loop share its variables, so the port stores what each declaration is
  and which one, and dispatches on that.
""", nkNim, "What changed in translation"

