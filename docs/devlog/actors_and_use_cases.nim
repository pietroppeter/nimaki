## What a use case diagram is

A *use case* diagram is one of the diagrams of UML. It shows who uses a system (*actors*: a
customer, a clerk, another system), what they can do with it (*use cases*: place an order, pay),
and where the system ends (the *boundary*, a box around its use cases). Lines say who takes part
in what; a dotted arrow marked «include» says one use case always runs another, «extend» that it
sometimes adds to it. Mermaid added them in version 12, as `usecase-beta`, and adds a node of its
own: a `json` table, for the data a use case works on.
"""

