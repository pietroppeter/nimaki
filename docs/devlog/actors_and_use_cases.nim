## A parser that looks ahead

The parsers ported so far were generated by Jison, which reads one token at a time and keeps a
table of what may come next. Mermaid reads use case diagrams with
[Chevrotain](https://chevrotain.io/), where the grammar is written as code, and each choice
between rules is decided by looking at most three tokens ahead. Pele does not run Chevrotain: it
makes the same decisions from the same lookahead by hand, so that it accepts the same texts and
names the same token when it fails. The port follows it.

The lexer comes first. Here are the tokens of one line:
"""

